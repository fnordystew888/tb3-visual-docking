"""Summarise results/data/experiments.csv into tables (markdown) and figures.

Usage: python scripts/make_plots.py
Outputs: results/summary.md, results/figures/*.png
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from tb3nav.plots import trial_overview

ROOT = os.path.join(os.path.dirname(__file__), "..")
FIG = os.path.join(ROOT, "results", "figures")

ROBUST = ["nominal", "push_8N", "push_8N_no_recovery", "wheel_radius_+3%", "low_friction_0.3", "frame_drop_50%",
          "blind_8s", "image_noise_blur", "dim_light_40%", "combined", "odometry_only"]
RSWEEP = ["Rx0.01", "Rx0.1", "Rx1", "Rx3", "Rx10", "Rx30", "Rx100"]
QSWEEP = ["q_lat0.25", "q_lat2.5", "q_lat25", "q_lat250", "q_lat2500"]


def ci95(x):
    x = np.asarray(x, float)
    x = x[np.isfinite(x)]
    if len(x) < 2:
        return np.nan
    return 1.96 * x.std(ddof=1) / np.sqrt(len(x))


def table(df, conds):
    lines = ["| condition | n | success | dock error [cm] | est. RMSE after 3 s [cm] | max est. error [cm] | est. yaw RMSE [deg] | mean NEES | NEES < 7.81 | true path error [cm] | LQR cross-track on estimate [cm] | time [s] | EKF resets | collisions |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for c in conds:
        g = df[df.condition == c]
        if not len(g):
            continue
        f = lambda col, s=100: f"{g[col].mean()*s:.1f} ± {ci95(g[col])*s:.1f}"
        lines.append(f"| {c} | {len(g)} | {int(g.success.sum())}/{len(g)} | {f('dock_pos_err_m')} | {f('est_rmse_pos_after3s_m')} | "
                     f"{f('est_max_pos_m')} | {f('est_rmse_yaw_deg', 1)} | {g.nees_mean.mean():.2f} | {g.nees_in_95.mean()*100:.0f}% | "
                     f"{f('track_rmse_after3s_m')} | {f('ctrl_ct_rmse_m')} | {g.time_s.mean():.1f} | {g.ekf_resets.mean():.1f} | {int((g.collision_steps > 0).sum())} |")
    return "\n".join(lines)


def main():
    df = pd.read_csv(os.path.join(ROOT, "results", "data", "experiments.csv"))
    df["success"] = df["success"].astype(str).str.lower() == "true"
    md = ["# Experiment summary (auto-generated by scripts/make_plots.py)\n",
          "Values are mean ± 95% confidence half-width over seeded randomised trials (start pose and obstacle layout differ per seed). "
          "Success = docked with true position error < 5 cm and yaw error < 10 deg. 'True path error' is the distance of the TRUE robot from the active path; 'LQR cross-track on estimate' is the error the controller sees (estimate vs path). NEES for a consistent 3-state filter averages 3 and lies under 7.81 for 95% of steps.\n",
          "## Robustness\n", table(df, ROBUST), "\n## Measurement-noise scaling (R x k), condition: +3% wheel radius and 8 N push\n",
          table(df, RSWEEP), "\n## LQR cross-track weight q_lat, condition: 8 N push\n", table(df, QSWEEP)]
    with open(os.path.join(ROOT, "results", "summary.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    print("\n".join(md))

    # robustness bars
    g = df[df.condition.isin(ROBUST)]
    conds = [c for c in ROBUST if c in set(g.condition)]
    fig, ax = plt.subplots(1, 3, figsize=(15, 4.2))
    for a, col, lab, sc in zip(ax, ["dock_pos_err_m", "est_rmse_pos_after3s_m", "track_rmse_after3s_m"],
                               ["final dock error [cm]", "estimation RMSE after 3 s [cm]", "true path error RMSE [cm]"], [100, 100, 100]):
        data = [g[g.condition == c][col].values * sc for c in conds]
        a.boxplot(data, tick_labels=conds, showfliers=True)
        a.set_yscale("log")
        a.set_ylabel(lab)
        a.tick_params(axis="x", rotation=60)
        if col == "dock_pos_err_m":
            a.axhline(5, ls="--", c="r", lw=1, label="5 cm success threshold")
            a.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, "robustness.png"), dpi=130)
    plt.close(fig)

    # R sweep trade-off
    g = df[df.condition.isin(RSWEEP)]
    if len(g):
        ks = [float(c[2:]) for c in RSWEEP if c in set(g.condition)]
        cs = [c for c in RSWEEP if c in set(g.condition)]
        fig, ax = plt.subplots(1, 3, figsize=(14, 3.8))
        nees = [g[g.condition == c].nees_mean.mean() for c in cs]
        rmse = [g[g.condition == c].est_rmse_pos_after3s_m.mean() * 100 for c in cs]
        succ = [g[g.condition == c].success.mean() * 100 for c in cs]
        rej = [(g[g.condition == c].ekf_rejects / (g[g.condition == c].ekf_rejects + g[g.condition == c].ekf_updates)).mean() * 100 for c in cs]
        ax[0].semilogx(ks, nees, "o-"); ax[0].axhline(3, ls="--", c="k", label="ideal = 3"); ax[0].set_yscale("log")
        ax[0].set(xlabel="R scale k", ylabel="mean NEES", title="Consistency"); ax[0].legend()
        ax[1].semilogx(ks, rmse, "o-"); ax[1].set(xlabel="R scale k", ylabel="position RMSE after 3 s [cm]", title="Accuracy")
        a2 = ax[1].twinx(); a2.semilogx(ks, succ, "s--", c="g"); a2.set_ylabel("dock success [%]", color="g"); a2.set_ylim(-5, 105)
        ax[2].semilogx(ks, rej, "o-"); ax[2].set(xlabel="R scale k", ylabel="gated-out measurements [%]", title="Innovation gate rejections")
        fig.tight_layout(); fig.savefig(os.path.join(FIG, "r_sweep.png"), dpi=130); plt.close(fig)

    # LQR sweep trade-off
    g = df[df.condition.isin(QSWEEP)]
    if len(g):
        cs = [c for c in QSWEEP if c in set(g.condition)]
        fig, ax = plt.subplots(figsize=(5.5, 4))
        for c in cs:
            h = g[g.condition == c]
            ax.errorbar(h.effort.mean(), h.ctrl_ct_rmse_m.mean() * 100, xerr=ci95(h.effort), yerr=ci95(h.ctrl_ct_rmse_m) * 100, fmt="o", capsize=3, label=c + " (vs estimate)")
            ax.plot(h.effort.mean(), h.track_rmse_after3s_m.mean() * 100, "kx")
        ax.plot([], [], "kx", label="true path error")
        ax.set(xlabel=r"control effort $\int (v^2 + 0.1\,\omega^2)\,dt$", ylabel="cross-track RMSE after 3 s [cm]", title="LQR weight trade-off")
        ax.legend(); fig.tight_layout(); fig.savefig(os.path.join(FIG, "lqr_tradeoff.png"), dpi=130); plt.close(fig)

    # per-condition overview plots for the saved representative logs
    logdir = os.path.join(ROOT, "results", "data", "logs")
    for fn in sorted(os.listdir(logdir)) if os.path.isdir(logdir) else []:
        if fn.endswith(".npy") and fn[:-4] in ROBUST:
            log = np.load(os.path.join(logdir, fn), allow_pickle=True).item()
            trial_overview(log, os.path.join(FIG, f"trial_{fn[:-4]}.png"), title=f"{fn[:-4]} (seed 1000)")


if __name__ == "__main__":
    main()
